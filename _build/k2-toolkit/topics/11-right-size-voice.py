# Lee leads (Tee led Topic 10). The lesson is not "be quiet." It is "match my voice to the place": look around, pick my
# number, turn my voice dial, and walk over before I talk. Students learn a 0 to 4 voice chart and a hand gesture
# (pinch the fingers and twist, like turning a radio knob) that they use with the words "turn my dial."
#   0 Lips closed (hallway, when the teacher is talking)   1 Whisper (others are working)   2 Table talk (partners)
#   3 Share voice (talking to the whole class, so the back row can hear)   4 Outside voice (recess)
# Story: center time. Lee spots a ladybug on the plant by the window. "TEE, COME LOOK!" is ready to jump out across the
# room, but the teacher is reading with a small group at the back table. Lee stops, looks around, turns her dial to 1,
# walks over, and whispers, "Tee, come see!" Tee tiptoes over and whispers, "Wow!" The teacher smiles from the reading
# table. At recess they turn the dial all the way up: "Race you to the slide!" Too soft is not right-size either: when
# Tee shares with the class he turns his dial up to 3 so the back row can hear.
# Off-size voices belong to classmates (Kiara calls out across the room, Diego yells in the hallway, Malik mumbles when
# sharing), never Lee or Tee.
# Reused art: kiara_callout (library), kiara_shout, puzzle, ball, promise, leave, class_breathe.
