# Topic 11 · Right-Size Voice (draft 2; not published). Build: python3 build.py topics/11-right-size-voice.py
# Lee leads (Tee led Topic 10). The lesson is not "be quiet." It is "match my voice to the place," with the school's
# 0 to 4 voice levels, each tied to a real place in the school day:
#   0  Someone is talking to the group (teacher or a classmate), and walking in the hallway
#   1  Partner share and reading to myself (a whisper, just for my partner)
#   2  Cafeteria table talk (just for my table)
#   3  Presenting to the class, and gym class team games (the whole room or team can hear)
#   4  Outside at recess
# The "how": look around, ask "Who needs to hear me?", turn my dial (pinch the fingers and twist, like a radio knob),
# and check it again, because voices creep up. The question "Who needs to hear me?" is what makes the number make sense:
# nobody right now (0), just my partner (1), just my table (2), the whole room or team (3), friends far away outside (4).
# Story: Lee and Tee's day, one scene per level. The problem moment is lunch: the table starts at a 2, then the voices
# creep up (Kiara and Diego laughing louder and louder) until nobody can hear. Lee looks around, turns her dial, and
# says what to say: "Let's take it back to two!" The whole table turns it down. Too soft is not right-size either:
# when Tee presents his drawing, he uses a 3 so the back row can hear.
# Off-size voices belong to classmates (Kiara calls out while the teacher talks, Diego yells in the hallway, Malik
# mumbles when presenting, Kiara and Diego get loud at lunch), never Lee or Tee.
# Reused art: kiara_callout (library), promise, leave, class_breathe.
